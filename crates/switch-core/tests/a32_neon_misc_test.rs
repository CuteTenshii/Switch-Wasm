#[test]
fn the_two_register_miscellaneous_group_agrees_with_qemu() {
    for &(insn, before, after) in CASES {
        let mut cpu = cpu();
        let code: Vec<u32> = LOAD.into_iter().chain([insn]).chain(STORE).collect();
        load(&mut cpu, &code);
        for (i, &word) in before.iter().enumerate() {
            cpu.mem.write_u32(SCRATCH + 4 * i as u32, word).unwrap();
        }
        cpu.run(code.len() as u64 + 1).unwrap();
        let got: Vec<u32> = (0..12)
            .map(|i| cpu.mem.read_u32(SCRATCH + 0x100 + 4 * i).unwrap())
            .collect();
        assert_eq!(got, after, "{insn:#010x} on {before:08x?}");
    }
}
